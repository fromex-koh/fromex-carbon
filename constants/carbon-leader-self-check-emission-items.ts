export interface EmissionLeaf {
  id: string
  scope: string
  major: string
  mid: string
  name: string
}

export interface EmissionGroup {
  key: string
  /** 중분류명. 중분류가 없는 대분류는 빈 문자열 */
  mid: string
  leaves: EmissionLeaf[]
}

export interface EmissionMajor {
  key: string
  name: string
  required: boolean
  groups: EmissionGroup[]
  leaves: EmissionLeaf[]
}

export interface EmissionScope {
  key: string
  name: string
  majors: EmissionMajor[]
  leaves: EmissionLeaf[]
}

export const LEAVES: EmissionLeaf[] = RAW.flatMap(
  ([scope, major, mid, names]) =>
    names.map((name) => ({
      id: [scope, major, mid, name].join("|"),
      scope,
      major,
      mid,
      name,
    })),
)

const buildScopes = (): EmissionScope[] => {
  const scopes: EmissionScope[] = []

  RAW.forEach(([scopeName, majorName, mid]) => {
    const scopeKey = scopeName
    const majorKey = `${scopeName}||${majorName}`
    const groupKey = `${scopeName}||${majorName}||${mid}`

    let scope = scopes.find((item) => item.key === scopeKey)
    if (!scope) {
      scope = { key: scopeKey, name: scopeName, majors: [], leaves: [] }
      scopes.push(scope)
    }

    let major = scope.majors.find((item) => item.key === majorKey)
    if (!major) {
      major = {
        key: majorKey,
        name: majorName,
        required: REQUIRED_MAJORS.includes(majorName),
        groups: [],
        leaves: [],
      }
      scope.majors.push(major)
    }

    const leaves = LEAVES.filter(
      (leaf) =>
        leaf.scope === scopeName &&
        leaf.major === majorName &&
        leaf.mid === mid,
    )
    major.groups.push({ key: groupKey, mid, leaves })
    major.leaves.push(...leaves)
    scope.leaves.push(...leaves)
  })

  return scopes
}

export const SCOPES: EmissionScope[] = buildScopes()

export const GROUP_BY_KEY: Record<string, EmissionGroup> = Object.fromEntries(
  SCOPES.flatMap((scope) =>
    scope.majors.flatMap((major) =>
      major.groups.map((group) => [group.key, group] as const),
    ),
  ),
)

export const TOTAL_COUNT = LEAVES.length

/** 좌측에서 고른 분류의 제목: "Scope 1 · 에너지 · 고정 연소" */
export const groupLabel = (group: EmissionGroup) => {
  const [scope, major] = group.key.split("||")
  return [scope, major, group.mid].filter(Boolean).join(" · ")
}

/** 항목 우측 배지: "Scope 1 : 에너지 '고정 연소'" */
export const leafBadge = (leaf: EmissionLeaf) =>
  `${leaf.scope} : ${leaf.major}${leaf.mid ? ` ‘${leaf.mid}’` : ""}`

